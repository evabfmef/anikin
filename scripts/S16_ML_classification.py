"""
S16_ML_classification.py - Machine learning classification of kin discrimination groups

Author: Eva Stare

Applies supervised machine learning to binary presence/absence matrices (six
genomic feature classes) to identify accessory-genome features predictive of
kin discrimination (KD) group membership.

The same pipeline is applied independently to the 39-strain (14 KD groups) and
67-strain datasets; only the input file differs.

Methodology
-----------
Naive Bayes uses the Bernoulli implementation, which is the appropriate variant
for binary presence/absence data (the Gaussian variant assumes continuous
features). A regularised logistic regression is included as a linear baseline
and a stratified dummy classifier as a floor.

Cross-validation is repeated stratified k-fold with shuffling and fixed seeds
throughout, so results are reproducible. Because the smallest class contains
few strains, the number of folds is capped at the smallest class size.

Performance is reported as balanced accuracy and macro-F1 in addition to
accuracy and weighted F1: with strongly unequal class sizes the unweighted
metrics describe minority-class performance, which the weighted ones obscure.
Per-class recall and a pooled out-of-fold confusion matrix are also reported.

Class labels are validated against the classifier's own significance floor by
permutation testing: the observed balanced accuracy is compared against a null
distribution generated by repeatedly shuffling the labels.

Feature importance is computed out-of-fold. Within each fold the model is
fitted on the training split only and permutation importance is evaluated on
the held-out split, so importances are not read off a model that has already
seen the strain being scored. Random-forest impurity importance provides the 
ranked candidate list, computed both on the full dataset and within each fold so 
that consistently ranked features can be distinguished from unstable ones. It is 
not used to claim predictive validation, being computed in-sample. Ranking two 
models separately and intersecting arbitrary top-N lists is not used: agreement 
between two in-sample rankings does not establish out-of-sample relevance.

Out-of-fold permutation importance is near-zero for essentially all features in
both panels. This is not a failure of the analysis but a property of the data:
accessory features co-segregate so tightly that many carry equivalent
information, and permuting any single one leaves the remainder sufficient to
recover group membership. A feature-subsampling test quantifies this directly
by retraining on random subsets of decreasing size. Together these show that KD
group identity is encoded redundantly across many accessory features rather
than by individual determinants. Analyses that isolate within-lineage effects
are reported separately (pairwise enrichment across high-ANI strain pairs).

Group definition
----------------
KD groups containing <=2 strains are pooled into a single "KDoutgroups"
category. Strains in KDoutgroups are not kin to one another; the pooled class
is a heterogeneous "everything else" category and is interpreted only as such.
Per-class metrics are reported so its performance can be read separately from
the coherent multi-strain groups.

Cross-validation note
---------------------
Splitting is at the level of individual strains. Closely related strains can
therefore fall in both training and validation folds, so classification
performance partly reflects genomic relatedness among strains. Group-aware
splitting on genomovar identity is not applicable to this target: most
genomovars correspond to exactly one KD group, so holding out a genomovar would
remove an entire class from the training data. This is a property of the
classification target rather than of the splitter, and is stated as a
limitation rather than worked around.

Outputs
-------
  KD_model_random_forest.joblib, KD_model_bernoulli_nb.joblib,
  KD_model_svm.joblib, KD_model_logreg.joblib
  model_performance.xlsx        - all metrics, per-class recall, confusion matrix
  feature_importance_oof.xlsx   - out-of-fold permutation importance + stability
  feature_importances_rf.xlsx   - ranked candidate features (RF impurity, with
                                  per-fold mean, SD and top-N frequency)
  redundancy_subsampling.xlsx   - accuracy vs random feature-subset size
  ml_model_comparison.png       - per-fold score distributions

Environment
-----------
Run under the pinned environment in environment/S16_environment.yml. Fixed
seeds reproduce results only within a given scikit-learn version, so the pin is
required rather than optional; verify with environment/S16_verify_environment.py
before running.
"""

import importlib
import os

import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (accuracy_score, balanced_accuracy_score,
                             confusion_matrix, f1_score, recall_score)
from sklearn.model_selection import (RepeatedStratifiedKFold, StratifiedKFold,
                                     cross_val_score, cross_validate,
                                     permutation_test_score)
from sklearn.naive_bayes import BernoulliNB
from sklearn.svm import SVC

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
# --- Analysis selection: "39" or "67" -----------------------------------
ANALYSIS = "39"          # change to "39" for the 39-strain PS panel (14 KD groups)
if ANALYSIS not in ("39", "67"):
    raise ValueError(f"ANALYSIS must be '39' or '67', got {ANALYSIS!r}")

# Input workbooks, read directly (no TSV conversion step).
INPUT_FILES = {
    "39": ("data/kd/inputs/"
           "39PS_megamatrix.xlsx",
           "Filtered_mega"),
    "67": ("data/kd/inputs/"
           "67_megamatrix.xlsx",
           "Megamatrix"),
}
INPUT_FILE, SHEET_NAME = INPUT_FILES[ANALYSIS]

OUTPUT_DIR = f"data/kd/output/{ANALYSIS}"
os.makedirs(OUTPUT_DIR, exist_ok=True)

LABEL_COLS = ["label_gruped", "lab_label"]
TARGET_COL = "label_gruped"

# Fixed seed used for every stochastic step: model initialisation, fold
# assignment, permutation importance and permutation testing.
RANDOM_STATE = 42

N_REPEATS = 10        # CV repeats
N_PERMUTATIONS = 200   # label permutations for the significance test
N_PERM_REPEATS = 20   # permutation-importance repeats per fold
TOP_N = 200           # features screened per fold for permutation importance
SUBSET_FRACTIONS = [1.0, 0.5, 0.25, 0.10, 0.05, 0.01, 0.005]  # redundancy test
N_SUBSET_REPEATS = 10  # random subsets drawn per fraction
N_EXPORT = 100         # rows written to the ranked feature table

# Report package versions for reproducibility
for pkg in ["pandas", "numpy", "matplotlib", "seaborn", "sklearn", "joblib"]:
    try:
        print(f"{pkg}: {importlib.import_module(pkg).__version__}")
    except Exception as exc:
        print(f"{pkg}: ERROR ({exc})")

# ---------------------------------------------------------------------------
# 1. Load and validate data
# ---------------------------------------------------------------------------
data = pd.read_excel(INPUT_FILE, sheet_name=SHEET_NAME, index_col=0)

X = data.drop(columns=LABEL_COLS)
y = data[TARGET_COL]

# The feature matrix must be strictly binary: BernoulliNB, and the presence/
# absence interpretation throughout, assume 0/1 coding. Fail on anything else.
if X.isna().any().any():
    raise ValueError(f"Feature matrix contains {int(X.isna().sum().sum())} missing value(s).")

observed = set(pd.unique(X.values.ravel()))
if not observed <= {0, 1}:
    raise ValueError(f"Feature matrix is not binary; found {sorted(observed)[:10]}.")

# Invariant features carry no discriminatory information.
invariant = X.columns[(X.nunique() == 1)].tolist()
if invariant:
    print(f"Warning: {len(invariant)} invariant feature(s) present, e.g. {invariant[:5]}")

class_counts = y.value_counts().sort_index()
print(f"\nLoaded {X.shape[0]} strains x {X.shape[1]} features")
print(f"Classes ({y.nunique()}):")
for cls, n in class_counts.items():
    print(f"  {cls}: {n}")

# Every class must appear in every fold, so folds are capped at the smallest
# class size.
N_SPLITS = min(3, int(class_counts.min()))
if N_SPLITS < 2:
    raise ValueError(f"Smallest class has {class_counts.min()} member(s); cannot cross-validate.")
print(f"\nCross-validation: {N_SPLITS}-fold, {N_REPEATS} repeats, seed {RANDOM_STATE}")

# ---------------------------------------------------------------------------
# 2. Define models
# ---------------------------------------------------------------------------
# BernoulliNB is the Naive Bayes variant for binary features. LogisticRegression
# provides a regularised linear baseline (scikit-learn applies L2 by default);
# the stratified dummy gives the floor expected from class frequencies alone.
def build_models():
    """Return a fresh set of unfitted models with fixed seeds."""
    return {
        "Random Forest": RandomForestClassifier(random_state=RANDOM_STATE),
        "SVM": SVC(random_state=RANDOM_STATE),
        "Bernoulli NB": BernoulliNB(),
        "Logistic Regression": LogisticRegression(
            C=1.0, max_iter=5000, random_state=RANDOM_STATE),
        "Dummy": DummyClassifier(strategy="stratified", random_state=RANDOM_STATE),
    }


SCORERS = {
    "accuracy": "accuracy",
    "balanced_accuracy": "balanced_accuracy",
    "f1_weighted": "f1_weighted",
    "f1_macro": "f1_macro",
}

# ---------------------------------------------------------------------------
# 3. Cross-validated performance
# ---------------------------------------------------------------------------
cv = RepeatedStratifiedKFold(n_splits=N_SPLITS, n_repeats=N_REPEATS,
                             random_state=RANDOM_STATE)

cv_results = {}
for name, model in build_models().items():
    cv_results[name] = cross_validate(model, X, y, cv=cv, scoring=SCORERS)

rows = []
for name, scores in cv_results.items():
    row = {"Model": name}
    for metric in SCORERS:
        vals = scores[f"test_{metric}"]
        row[metric] = f"{vals.mean():.3f} (+/- {vals.std():.3f})"
    rows.append(row)

performance_df = pd.DataFrame(rows).set_index("Model")
print("\nCross-validated performance:")
print(performance_df.to_string())

# ---------------------------------------------------------------------------
# 4. Out-of-fold predictions: per-class recall and confusion matrix
# ---------------------------------------------------------------------------
# Predictions are collected from held-out folds only, so the confusion matrix
# describes generalisation rather than fit.
oof_cv = StratifiedKFold(n_splits=N_SPLITS, shuffle=True, random_state=RANDOM_STATE)
classes = np.array(sorted(y.unique()))

oof_pred = pd.Series(index=y.index, dtype=object)
for train_idx, test_idx in oof_cv.split(X, y):
    model = build_models()["Random Forest"]
    model.fit(X.iloc[train_idx], y.iloc[train_idx])
    oof_pred.iloc[test_idx] = model.predict(X.iloc[test_idx])

recall = recall_score(y, oof_pred, labels=classes, average=None, zero_division=0)
per_class_df = pd.DataFrame({
    "class": classes,
    "n_strains": [int((y == c).sum()) for c in classes],
    "recall": recall,
})

cm = confusion_matrix(y, oof_pred, labels=classes)
cm_df = pd.DataFrame(cm, index=[f"true_{c}" for c in classes],
                     columns=[f"pred_{c}" for c in classes])

print("\nOut-of-fold per-class recall (Random Forest):")
print(per_class_df.to_string(index=False))
print("\nOut-of-fold confusion matrix:")
print(cm_df.to_string())
print(f"\nOut-of-fold balanced accuracy: {balanced_accuracy_score(y, oof_pred):.3f}")
print(f"Out-of-fold macro F1:         {f1_score(y, oof_pred, average='macro'):.3f}")

# ---------------------------------------------------------------------------
# 5. Permutation test
# ---------------------------------------------------------------------------
# Compares observed balanced accuracy against a null distribution obtained by
# shuffling the class labels, giving an empirical p-value for the classifier.
print(f"\nPermutation test ({N_PERMUTATIONS} permutations)...")
perm_score, perm_scores, perm_pvalue = permutation_test_score(
    build_models()["Random Forest"], X, y,
    scoring="balanced_accuracy",
    cv=StratifiedKFold(n_splits=N_SPLITS, shuffle=True, random_state=RANDOM_STATE),
    n_permutations=N_PERMUTATIONS,
    random_state=RANDOM_STATE,
    n_jobs=-1,
)
print(f"  observed balanced accuracy: {perm_score:.3f}")
print(f"  permuted mean (null):       {perm_scores.mean():.3f} +/- {perm_scores.std():.3f}")
print(f"  empirical p-value:          {perm_pvalue:.4f}")

permutation_df = pd.DataFrame({
    "metric": ["observed_balanced_accuracy", "null_mean", "null_sd",
               "p_value", "n_permutations"],
    "value": [perm_score, perm_scores.mean(), perm_scores.std(),
              perm_pvalue, N_PERMUTATIONS],
})

# ---------------------------------------------------------------------------
# 6. Out-of-fold permutation importance and selection stability
# ---------------------------------------------------------------------------
# Within each fold the model is fitted on the training split and importance is
# measured on the held-out split, so no feature is scored on a strain used to
# fit the model. Evaluating all features is computationally prohibitive, so
# each fold is screened to the TOP_N features by training-split impurity
# importance and the model is refitted on that subset before permutation.
print(f"\nOut-of-fold permutation importance "
      f"({N_SPLITS} folds x {N_REPEATS} repeats, top {TOP_N} screened per fold)...")

stability_cv = RepeatedStratifiedKFold(n_splits=N_SPLITS, n_repeats=N_REPEATS,
                                       random_state=RANDOM_STATE)

fold_importances = []
for train_idx, test_idx in stability_cv.split(X, y):
    X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
    y_train, y_test = y.iloc[train_idx], y.iloc[test_idx]

    screen = build_models()["Random Forest"].fit(X_train, y_train)
    screened = (pd.Series(screen.feature_importances_, index=X.columns)
                .nlargest(TOP_N).index.tolist())

    model = build_models()["Random Forest"].fit(X_train[screened], y_train)
    result = permutation_importance(
        model, X_test[screened], y_test,
        scoring="balanced_accuracy",
        n_repeats=N_PERM_REPEATS,
        random_state=RANDOM_STATE,
        n_jobs=-1,
    )
    fold_importances.append(pd.Series(result.importances_mean, index=screened))
    print(f"  fold {len(fold_importances)}/{N_SPLITS * N_REPEATS} done")

importance_matrix = pd.concat(fold_importances, axis=1)
n_folds = importance_matrix.shape[1]

oof_importance = pd.DataFrame({
    "Feature": importance_matrix.index,
    "Mean_importance": importance_matrix.mean(axis=1).values,
    "SD_importance": importance_matrix.std(axis=1).values,
    "Folds_evaluated": importance_matrix.notna().sum(axis=1).values,
    "Folds_positive": (importance_matrix > 0).sum(axis=1).values,
}).sort_values("Mean_importance", ascending=False).reset_index(drop=True)
oof_importance["Stability"] = (oof_importance["Folds_positive"]
                               / oof_importance["Folds_evaluated"])

n_eval = len(oof_importance)
n_ever = int((oof_importance["Folds_positive"] > 0).sum())
n_majority = int((oof_importance["Stability"] >= 0.5).sum())

print(f"  features evaluated in >=1 fold:          {n_eval}")
print(f"  positive held-out importance in any fold: {n_ever}")
print(f"  positive in >=50% of folds:               {n_majority}")
if n_ever:
    print(f"  max folds any feature was positive:       "
          f"{int(oof_importance['Folds_positive'].max())}/{n_folds}")
print("\n  Interpretation: features with no reproducible held-out importance are "
      "\n  not uninformative, but individually redundant - the information they "
      "\n  carry is duplicated across other co-segregating features.")

# ---------------------------------------------------------------------------
# 6b. Redundancy test: performance on random feature subsets
# ---------------------------------------------------------------------------
# Direct test of distributed encoding. If group identity depended on a small
# number of specific determinants, discarding most features at random would
# usually remove them and accuracy would collapse. If it is encoded redundantly
# across many features, accuracy is retained.
print(f"\nRedundancy test: retraining on random feature subsets "
      f"({N_SUBSET_REPEATS} subsets per fraction)...")

subset_cv = StratifiedKFold(n_splits=N_SPLITS, shuffle=True,
                            random_state=RANDOM_STATE)
rng = np.random.default_rng(RANDOM_STATE)

subset_rows = []
for frac in SUBSET_FRACTIONS:
    n_feat = max(1, int(round(frac * X.shape[1])))
    reps = 1 if frac >= 1.0 else N_SUBSET_REPEATS
    scores = []
    for _ in range(reps):
        cols = (X.columns if frac >= 1.0
                else rng.choice(X.columns, size=n_feat, replace=False))
        scores.append(cross_val_score(
            build_models()["Random Forest"], X[cols], y,
            cv=subset_cv, scoring="balanced_accuracy").mean())
    subset_rows.append({
        "Fraction_retained": frac,
        "N_features": n_feat,
        "N_random_subsets": reps,
        "Balanced_accuracy_mean": float(np.mean(scores)),
        "Balanced_accuracy_sd": float(np.std(scores)),
    })
    print(f"  {frac:6.3f}  n={n_feat:6d}  "
          f"balanced accuracy {np.mean(scores):.3f} +/- {np.std(scores):.3f}")

redundancy_df = pd.DataFrame(subset_rows)
full_acc = redundancy_df.iloc[0]["Balanced_accuracy_mean"]
tenth = redundancy_df[redundancy_df["Fraction_retained"] == 0.10]
if len(tenth):
    print(f"\n  Retaining 10% of features at random: "
          f"{tenth.iloc[0]['Balanced_accuracy_mean']:.3f} vs {full_acc:.3f} for all "
          f"{X.shape[1]} features.")

# ---------------------------------------------------------------------------
# 7. Random-forest impurity importance (in-sample, descriptive)
# ---------------------------------------------------------------------------
# Ranked candidate list. Impurity importance measures how much each feature
# contributed to separating the classes in the fitted trees; it is computed on
# training data and therefore identifies features that co-segregate with group
# identity, not features individually required for classification (see the
# out-of-fold result above).
#
# Importance is also recomputed within each cross-validation fold. A feature
# ranking highly in a single fit on all strains may do so by chance; reporting
# the mean, dispersion and top-N frequency across folds distinguishes
# consistently ranked features from unstable ones.
print(f"\nRandom-forest impurity importance "
      f"({N_SPLITS} folds x {N_REPEATS} repeats, plus a full-data fit)...")

impurity_cv = RepeatedStratifiedKFold(n_splits=N_SPLITS, n_repeats=N_REPEATS,
                                      random_state=RANDOM_STATE)

fold_impurity = []
for train_idx, _ in impurity_cv.split(X, y):
    model = build_models()["Random Forest"].fit(X.iloc[train_idx], y.iloc[train_idx])
    fold_impurity.append(pd.Series(model.feature_importances_, index=X.columns))

impurity_folds = pd.concat(fold_impurity, axis=1)
n_impurity_folds = impurity_folds.shape[1]

# Frequency with which each feature ranks in the top N_EXPORT within a fold.
fold_top_sets = [set(impurity_folds[c].nlargest(N_EXPORT).index)
                 for c in impurity_folds.columns]

# Full-data fit: the ranking reported in the manuscript.
rf_full = build_models()["Random Forest"].fit(X, y)

rf_importance = pd.DataFrame({
    "Feature": X.columns,
    "Impurity_importance": rf_full.feature_importances_,
    "Fold_mean": impurity_folds.mean(axis=1).values,
    "Fold_SD": impurity_folds.std(axis=1).values,
    f"Folds_in_top{N_EXPORT}": [sum(f in st for st in fold_top_sets) for f in X.columns],
}).sort_values("Impurity_importance", ascending=False).reset_index(drop=True)

rf_importance[f"Top{N_EXPORT}_frequency"] = (
    rf_importance[f"Folds_in_top{N_EXPORT}"] / n_impurity_folds)

top_export = rf_importance.head(N_EXPORT)
n_consistent = int((top_export[f"Top{N_EXPORT}_frequency"] >= 0.5).sum())
print(f"  of the top {N_EXPORT} features, {n_consistent} rank in the top "
      f"{N_EXPORT} in >=50% of folds")
print(f"\nTop 15 by impurity importance:")
print(top_export.head(15).to_string(index=False))

# ---------------------------------------------------------------------------
# 8. Fit and save final models
# ---------------------------------------------------------------------------
for name, model in build_models().items():
    if name == "Dummy":
        continue
    model.fit(X, y)
    safe = name.lower().replace(" ", "_")
    path = os.path.join(OUTPUT_DIR, f"KD_model_{safe}.joblib")
    joblib.dump(model, path)
    print(f"Saved: {path}")

# ---------------------------------------------------------------------------
# 9. Visualisation
# ---------------------------------------------------------------------------
fig, axes = plt.subplots(1, 2, figsize=(14, 6))
for ax, metric, title in [(axes[0], "balanced_accuracy", "Balanced accuracy"),
                          (axes[1], "f1_macro", "Macro F1")]:
    scores_df = pd.DataFrame(
        {name: res[f"test_{metric}"] for name, res in cv_results.items()})
    sns.boxplot(data=scores_df, ax=ax)
    ax.set_title(title)
    ax.set_ylabel(title)
    ax.set_xlabel("Model")
    ax.tick_params(axis="x", rotation=30)

plt.tight_layout()
plt.savefig(os.path.join(OUTPUT_DIR, "ml_model_comparison.png"),
            dpi=300, bbox_inches="tight")
plt.close()
print(f"Saved: {OUTPUT_DIR}/ml_model_comparison.png")

# ---------------------------------------------------------------------------
# 10. Export
# ---------------------------------------------------------------------------
with pd.ExcelWriter(os.path.join(OUTPUT_DIR, "model_performance.xlsx"),
                    engine="openpyxl") as writer:
    performance_df.to_excel(writer, sheet_name="CV_performance")
    per_class_df.to_excel(writer, sheet_name="Per_class_recall", index=False)
    cm_df.to_excel(writer, sheet_name="Confusion_matrix")
    permutation_df.to_excel(writer, sheet_name="Permutation_test", index=False)

with pd.ExcelWriter(os.path.join(OUTPUT_DIR, "feature_importance_oof.xlsx"),
                    engine="openpyxl") as writer:
    oof_importance.to_excel(writer, sheet_name="OOF_importance", index=False)

redundancy_df.to_excel(
    os.path.join(OUTPUT_DIR, "redundancy_subsampling.xlsx"), index=False)

top_export.to_excel(
    os.path.join(OUTPUT_DIR, "feature_importances_rf.xlsx"), index=False)

print(f"\nSaved to: {OUTPUT_DIR}")
